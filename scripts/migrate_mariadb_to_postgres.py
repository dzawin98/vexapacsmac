MYSQL = dict(host="localhost", port=3306, user="root", password="nexia")
POSTGRES = dict(host="localhost", port=5432, user="postgres", password="velo")
DATABASES = ("veloris_db", "velopacs_db")


def pg_type(column):
    data_type = column["DATA_TYPE"].lower()
    if data_type in {"tinyint", "smallint"}:
        return "SMALLINT"
    if data_type in {"int", "mediumint"}:
        return "INTEGER"
    if data_type == "bigint":
        return "BIGINT"
    if data_type in {"float", "double", "real"}:
        return "DOUBLE PRECISION"
    if data_type in {"decimal", "numeric"}:
        precision = column["NUMERIC_PRECISION"] or 38
        scale = column["NUMERIC_SCALE"] or 0
        return f"NUMERIC({precision},{scale})"
    if data_type in {"datetime", "timestamp"}:
        return "TIMESTAMP"
    if data_type == "date":
        return "DATE"
    if data_type == "time":
        return "TIME"
    if data_type in {"blob", "binary", "varbinary", "longblob", "mediumblob", "tinyblob"}:
        return "BYTEA"
    if data_type in {"char", "varchar"}:
        length = column["CHARACTER_MAXIMUM_LENGTH"] or 255
        return f"VARCHAR({length})"
    return "TEXT"


def normalize(value):
    if isinstance(value, (datetime, date, time, bytes, bytearray, memoryview)):
        return value
    if isinstance(value, (dict, list)):
        return json.dumps(value, ensure_ascii=False)
    return value


def migrate_database(name):
    print(f"[DATABASE] {name}")
    with psycopg.connect(dbname="postgres", autocommit=True, **POSTGRES) as admin:
        admin.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(name)))
        admin.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))

    mysql = pymysql.connect(database=name, cursorclass=pymysql.cursors.DictCursor, **MYSQL)
    pg = psycopg.connect(dbname=name, **POSTGRES)
    try:
        with mysql.cursor() as cur:
            cur.execute(
                "SELECT table_name AS TABLE_NAME FROM information_schema.tables "
                "WHERE table_schema=%s AND table_type='BASE TABLE' ORDER BY table_name",
                (name,),
            )
            tables = [row["TABLE_NAME"] for row in cur.fetchall()]

        for table in tables:
            with mysql.cursor() as cur:
                cur.execute(
                    "SELECT * FROM information_schema.columns WHERE table_schema=%s AND table_name=%s "
                    "ORDER BY ordinal_position",
                    (name, table),
                )
                columns = cur.fetchall()
                cur.execute(
                    "SELECT constraint_name AS CONSTRAINT_NAME, constraint_type AS CONSTRAINT_TYPE FROM information_schema.table_constraints "
                    "WHERE table_schema=%s AND table_name=%s "
                    "AND constraint_type IN ('PRIMARY KEY','UNIQUE')",
                    (name, table),
                )
                constraints = cur.fetchall()
                constraint_columns = {}
                for constraint in constraints:
                    cur.execute(
                        "SELECT column_name AS COLUMN_NAME FROM information_schema.key_column_usage "
                        "WHERE table_schema=%s AND table_name=%s AND constraint_name=%s "
                        "ORDER BY ordinal_position",
                        (name, table, constraint["CONSTRAINT_NAME"]),
                    )
                    constraint_columns[constraint["CONSTRAINT_NAME"]] = [
                        row["COLUMN_NAME"] for row in cur.fetchall()
                    ]

            definitions = []
            for column in columns:
                definition = sql.SQL("{} {}").format(
                    sql.Identifier(column["COLUMN_NAME"]), sql.SQL(pg_type(column))
                )
                if "auto_increment" in (column["EXTRA"] or ""):
                    definition += sql.SQL(" GENERATED BY DEFAULT AS IDENTITY")
                if column["IS_NULLABLE"] == "NO":
                    definition += sql.SQL(" NOT NULL")
                definitions.append(definition)
            for constraint in constraints:
                cols = sql.SQL(", ").join(sql.Identifier(c) for c in constraint_columns[constraint["CONSTRAINT_NAME"]])
                if constraint["CONSTRAINT_TYPE"] == "PRIMARY KEY":
                    definitions.append(sql.SQL("PRIMARY KEY ({})").format(cols))
                else:
                    definitions.append(sql.SQL("UNIQUE ({})").format(cols))

            with pg.cursor() as cur:
                cur.execute(
                    sql.SQL("CREATE TABLE {} ({})").format(
                        sql.Identifier(table), sql.SQL(", ").join(definitions)
                    )
                )

            names = [column["COLUMN_NAME"] for column in columns]
            with mysql.cursor() as cur:
                cur.execute(f"SELECT * FROM `{table}`")
                rows = cur.fetchall()
            if rows:
                statement = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
                    sql.Identifier(table),
                    sql.SQL(", ").join(sql.Identifier(n) for n in names),
                    sql.SQL(", ").join(sql.Placeholder() for _ in names),
                )
                with pg.cursor() as cur:
                    cur.executemany(statement, [[normalize(row[n]) for n in names] for row in rows])
            print(f"  {table}: {len(rows)} row(s)")

        with pg.cursor() as cur:
            cur.execute(
                "SELECT table_name, column_name FROM information_schema.columns "
                "WHERE table_schema='public' AND is_identity='YES'"
            )
            for table, column in cur.fetchall():
                cur.execute(
                    sql.SQL(
                        "SELECT setval(pg_get_serial_sequence(%s, %s), "
                        "GREATEST(COALESCE(MAX({}), 0), 1), COALESCE(MAX({}), 0) > 0) FROM {}"
                    ).format(sql.Identifier(column), sql.Identifier(column), sql.Identifier(table)),
                    (table, column),
                )
        pg.commit()
    finally:
        mysql.close()
        pg.close()


for database in DATABASES:
    migrate_database(database)
print("[DONE] MariaDB data migrated to PostgreSQL.")
