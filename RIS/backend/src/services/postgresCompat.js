const { Pool } = require('pg');

function replaceDateFormat(match, expression, format) {
  const pgFormat = format
    .replace(/%Y/g, 'YYYY').replace(/%m/g, 'MM').replace(/%d/g, 'DD')
    .replace(/%H/g, 'HH24').replace(/%i/g, 'MI').replace(/%s/g, 'SS');
  return `TO_CHAR(${expression}, '${pgFormat}')`;
}

function replaceFunctionCalls(input, functionName, replacer) {
  const marker = new RegExp(`${functionName}\\s*\\(`, 'ig');
  let sql = input;
  let match;
  while ((match = marker.exec(sql))) {
    const open = match.index + match[0].lastIndexOf('(');
    let depth = 1;
    let quote = '';
    let close = open + 1;
    for (; close < sql.length && depth > 0; close += 1) {
      const char = sql[close];
      if (quote) {
        if (char === quote && sql[close - 1] !== '\\') quote = '';
        continue;
      }
      if (char === "'" || char === '"') {
        quote = char;
      } else if (char === '(') {
        depth += 1;
      } else if (char === ')') {
        depth -= 1;
      }
    }
    if (depth !== 0) break;
    const body = sql.slice(open + 1, close - 1);
    const parts = [];
    let start = 0;
    depth = 0;
    quote = '';
    for (let index = 0; index < body.length; index += 1) {
      const char = body[index];
      if (quote) {
        if (char === quote && body[index - 1] !== '\\') quote = '';
        continue;
      }
      if (char === "'" || char === '"') quote = char;
      else if (char === '(') depth += 1;
      else if (char === ')') depth -= 1;
      else if (char === ',' && depth === 0) {
        parts.push(body.slice(start, index).trim());
        start = index + 1;
      }
    }
    parts.push(body.slice(start).trim());
    const replacement = replacer(parts);
    if (!replacement) {
      marker.lastIndex = close;
      continue;
    }
    sql = `${sql.slice(0, match.index)}${replacement}${sql.slice(close)}`;
    marker.lastIndex = match.index + replacement.length;
  }
  return sql;
}

function replaceTimestampDiff(input) {
  return replaceFunctionCalls(input, 'TIMESTAMPDIFF', (parts) => {
    if (parts.length !== 3) return null;
    const unit = parts[0].toUpperCase();
    const divisor = {
      SECOND: '1',
      MINUTE: '60',
      HOUR: '3600',
      DAY: '86400',
    }[unit];
    return divisor ? `TRUNC(EXTRACT(EPOCH FROM (${parts[2]}) - (${parts[1]})) / ${divisor})` : null;
  });
}

function replaceDateFormats(input) {
  return replaceFunctionCalls(input, 'DATE_FORMAT', (parts) => {
    if (parts.length !== 2) return null;
    const format = parts[1].replace(/^['"]|['"]$/g, '');
    return replaceDateFormat('', parts[0], format);
  });
}

function translateSql(input) {
  let sql = replaceDateFormats(replaceTimestampDiff(String(input)));
  sql = sql.replace(/`/g, '')
    .replace(/\bAUTO_INCREMENT\b/gi, 'GENERATED BY DEFAULT AS IDENTITY')
    .replace(/\bENUM\s*\([^)]*\)/gi, 'TEXT')
    .replace(/\bTINYINT\s*\(\s*1\s*\)/gi, 'SMALLINT')
    .replace(/\bTINYINT\b/gi, 'SMALLINT')
    .replace(/\bMEDIUMTEXT\b|\bLONGTEXT\b/gi, 'TEXT')
    .replace(/\bDATETIME\s*\(\s*(\d+)\s*\)/gi, 'TIMESTAMP($1)')
    .replace(/\bDATETIME\b/gi, 'TIMESTAMP')
    .replace(/\bDOUBLE\b/gi, 'DOUBLE PRECISION')
    .replace(/\bUNSIGNED\b/gi, '')
    .replace(/\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP(?:\(\d+\))?/gi, '')
    .replace(/\s+AFTER\s+"?[A-Za-z0-9_]+"?/gi, '')
    .replace(/\s+ENGINE\s*=\s*\w+/gi, '')
    .replace(/\s+DEFAULT\s+CHARSET\s*=\s*\w+/gi, '')
    .replace(/\s+COLLATE\s*=\s*\w+/gi, '')
    .replace(/\s+CHECK\s*\(\s*json_valid\s*\([^)]*\)\s*\)/gi, '')
    .replace(/"([^"]*)"/g, "'$1'")
    .replace(/\bIFNULL\s*\(/gi, 'COALESCE(')
    .replace(/\s*<=>\s*/g, ' IS NOT DISTINCT FROM ')
    .replace(/\bNOW\(\)/gi, 'CURRENT_TIMESTAMP')
    .replace(/\bCURDATE\(\)/gi, 'CURRENT_DATE')
    .replace(/DATE_ADD\s*\(\s*([^,]+?)\s*,\s*INTERVAL\s+(\d+)\s+(SECOND|MINUTE|HOUR|DAY)\s*\)/gi, "$1 + INTERVAL '$2 $3'")
    .replace(/DATE_SUB\s*\(\s*([^,]+?)\s*,\s*INTERVAL\s+(\d+)\s+(SECOND|MINUTE|HOUR|DAY)\s*\)/gi, "$1 - INTERVAL '$2 $3'")
    .replace(/GROUP_CONCAT\s*\(\s*DISTINCT\s+(\w+)\s+ORDER\s+BY\s+\1\s+SEPARATOR\s+['"]\\\\['"]\s*\)/gi, "STRING_AGG(DISTINCT $1, '\\\\' ORDER BY $1)")
    .replace(/\bINSERT\s+IGNORE\b/gi, 'INSERT')
    .replace(/\bVALUES\s*\(\s*([A-Za-z0-9_]+)\s*\)/gi, 'EXCLUDED.$1');
  sql = sql.replace(/\bALTER\s+TABLE\s+(\S+)\s+ADD\s+COLUMN\s+(?!IF\s+NOT\s+EXISTS)/gi, 'ALTER TABLE $1 ADD COLUMN IF NOT EXISTS ');
  sql = sql.replace(
    /^\s*DELETE\s+(\w+)\s+FROM\s+(\S+)\s+\1\s+INNER\s+JOIN\s+(\S+)\s+(\w+)\s+ON\s+(.+?)\s+WHERE\s+([\s\S]+)$/i,
    'DELETE FROM $2 $1 USING $3 $4 WHERE $5 AND $6',
  );
  sql = sql.replace(
    /^\s*ALTER\s+TABLE\s+(\S+)\s+ADD\s+(UNIQUE\s+)?INDEX\s+IF\s+NOT\s+EXISTS\s+(\S+)\s*\(([^)]+)\)\s*$/i,
    'CREATE $2INDEX IF NOT EXISTS $3 ON $1 ($4)',
  );
  sql = sql.replace(
    /^\s*ALTER\s+TABLE\s+(\S+)\s+DROP\s+FOREIGN\s+KEY\s+(\S+)\s*$/i,
    'ALTER TABLE $1 DROP CONSTRAINT IF EXISTS $2',
  );
  sql = sql.replace(
    /^\s*ALTER\s+TABLE\s+\S+\s+DROP\s+INDEX\s+(\S+)\s*$/i,
    'DROP INDEX IF EXISTS $1',
  );
  sql = sql.replace(
    /^\s*ALTER\s+TABLE\s+(\S+)\s+DROP\s+COLUMN\s+(?!IF\s+EXISTS)(\S+)\s*$/i,
    'ALTER TABLE $1 DROP COLUMN IF EXISTS $2',
  );
  sql = sql.replace(
    /^\s*ALTER\s+TABLE\s+(\S+)\s+MODIFY\s+COLUMN\s+(\S+)\s+([A-Z]+(?:\s*\([^)]*\))?)(?:\s+(?:NULL|NOT\s+NULL))?\s*$/i,
    'ALTER TABLE $1 ALTER COLUMN $2 TYPE $3',
  );
  sql = sql.replace(
    /^\s*UPDATE\s+(\S+)\s+SET\s+([\s\S]+?)\s+ORDER\s+BY\s+([\s\S]+?)\s+LIMIT\s+(\d+)\s*$/i,
    'UPDATE $1 SET $2 WHERE ctid IN (SELECT ctid FROM $1 ORDER BY $3 LIMIT $4)',
  );

  if (/CREATE\s+TABLE/i.test(sql)) {
    sql = sql.replace(/,\s*(?:INDEX|KEY)(?:\s+\w+)?\s*\([^)]*\)/gi, '')
      .replace(/,\s*UNIQUE\s+KEY\s+\w+\s*\(([^)]*)\)/gi, ', UNIQUE ($1)');
  }
  return sql;
}

function expandParams(sql, params = []) {
  const flat = [];
  let index = 0;
  const text = sql.replace(/\?/g, () => {
    const value = params[index++];
    if (Array.isArray(value) && value.length && Array.isArray(value[0])) {
      return value.map((row) => `(${row.map((cell) => {
        flat.push(cell);
        return `$${flat.length}`;
      }).join(', ')})`).join(', ');
    }
    if (Array.isArray(value)) {
      return value.map((cell) => {
        flat.push(cell);
        return `$${flat.length}`;
      }).join(', ');
    }
    flat.push(value);
    return `$${flat.length}`;
  });
  return { text, values: flat };
}

async function conflictTarget(client, sql) {
  const match = sql.match(/INSERT\s+INTO\s+"?([A-Za-z0-9_]+)"?/i);
  if (!match) return [];
  const insertedColumns = new Set(
    (sql.match(/INSERT\s+INTO\s+"?[A-Za-z0-9_]+"?\s*\(([^)]*)\)/i)?.[1] || '')
      .split(',')
      .map((column) => column.trim().replace(/^"|"$/g, ''))
      .filter(Boolean),
  );
  const result = await client.query(`
    SELECT array_agg(a.attname ORDER BY x.ord) AS columns
    FROM pg_index i
    JOIN LATERAL unnest(i.indkey) WITH ORDINALITY x(attnum, ord) ON true
    JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = x.attnum
    WHERE i.indrelid = $1::regclass AND (i.indisprimary OR i.indisunique)
    GROUP BY i.indexrelid
  `, [match[1]]);
  const candidates = result.rows
    .map((row) => row.columns)
    .map((raw) => Array.isArray(raw)
      ? raw
      : String(raw || '').replace(/^\{|\}$/g, '').split(',').filter(Boolean))
    .filter((columns) => columns.length && columns.every((column) => insertedColumns.has(column)))
    .sort((a, b) => a.length - b.length);
  const raw = candidates[0];
  return Array.isArray(raw)
    ? raw
    : String(raw || '').replace(/^\{|\}$/g, '').split(',').filter(Boolean);
}

async function prepare(client, input, params) {
  let sql = translateSql(input);
  if (/ON\s+DUPLICATE\s+KEY\s+UPDATE/i.test(sql)) {
    const columns = await conflictTarget(client, sql);
    if (!columns.length) throw new Error(`No PostgreSQL unique key found for upsert: ${sql.slice(0, 100)}`);
    sql = sql.replace(/ON\s+DUPLICATE\s+KEY\s+UPDATE/i, `ON CONFLICT (${columns.map((c) => `"${c}"`).join(', ')}) DO UPDATE SET`);
    const table = sql.match(/INSERT\s+INTO\s+"?([A-Za-z0-9_]+)"?/i)?.[1];
    if (table) {
      sql = sql.replace(/COALESCE\(\s*(EXCLUDED\.[A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)\s*\)/gi, `COALESCE($1, ${table}.$2)`);
      sql = sql.replace(/COALESCE\(\s*([A-Za-z0-9_]+)\s*,\s*(EXCLUDED\.[A-Za-z0-9_]+)\s*\)/gi, `COALESCE(${table}.$1, $2)`);
    }
  }
  if (/^\s*INSERT\s+/i.test(sql) && !/ON\s+CONFLICT/i.test(sql) && /\bIGNORE\b/i.test(input)) {
    sql += ' ON CONFLICT DO NOTHING';
  }
  return expandParams(sql, params);
}

const idColumnCache = new Map();
async function hasIdColumn(client, sql) {
  const table = sql.match(/INSERT\s+INTO\s+"?([A-Za-z0-9_]+)"?/i)?.[1];
  if (!table) return false;
  if (idColumnCache.has(table)) return idColumnCache.get(table);
  const result = await client.query(
    `SELECT EXISTS (
       SELECT 1 FROM information_schema.columns
       WHERE table_schema='public' AND table_name=$1 AND column_name='id'
     ) AS present`,
    [table],
  );
  const present = Boolean(result.rows[0]?.present);
  idColumnCache.set(table, present);
  return present;
}

function wrap(client, release = () => {}) {
  return {
    async query(sql, params = []) {
      const prepared = await prepare(client, sql, params);
      const isInsert = /^\s*INSERT\s+/i.test(prepared.text);
      if (isInsert && !/\bRETURNING\b/i.test(prepared.text) && await hasIdColumn(client, prepared.text)) prepared.text += ' RETURNING id';
      let result;
      try {
        result = await client.query(prepared.text, prepared.values);
      } catch (error) {
        error.message += `\nPostgreSQL SQL: ${prepared.text}`;
        throw error;
      }
      if (/^\s*(SELECT|WITH)\b/i.test(prepared.text)) return [result.rows, result.fields];
      return [{ affectedRows: result.rowCount || 0, insertId: result.rows[0]?.id || 0 }, result.fields];
    },
    async beginTransaction() { await client.query('BEGIN'); },
    async commit() { await client.query('COMMIT'); },
    async rollback() { await client.query('ROLLBACK'); },
    release,
  };
}

function createPool(config) {
  const pool = new Pool({
    host: config.host, port: config.port, user: config.user,
    password: config.password, database: config.database,
    max: config.connectionLimit || 10,
  });
  const api = wrap(pool);
  api.getConnection = async () => {
    const client = await pool.connect();
    return wrap(client, () => client.release());
  };
  api.end = () => pool.end();
  return api;
}

module.exports = { createPool, translateSql };
