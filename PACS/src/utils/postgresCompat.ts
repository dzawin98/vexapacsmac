import { Pool, PoolClient } from 'pg';

function translateSql(input: string): string {
  let sql = String(input).replace(/`/g, '')
    .replace(/\bAUTO_INCREMENT\b/gi, 'GENERATED BY DEFAULT AS IDENTITY')
    .replace(/\bENUM\s*\([^)]*\)/gi, 'TEXT')
    .replace(/\bTINYINT\s*\(\s*1\s*\)/gi, 'SMALLINT').replace(/\bTINYINT\b/gi, 'SMALLINT')
    .replace(/\bMEDIUMTEXT\b|\bLONGTEXT\b/gi, 'TEXT')
    .replace(/\bDATETIME\s*\(\s*(\d+)\s*\)/gi, 'TIMESTAMP($1)').replace(/\bDATETIME\b/gi, 'TIMESTAMP')
    .replace(/\bDOUBLE\b/gi, 'DOUBLE PRECISION').replace(/\bUNSIGNED\b/gi, '')
    .replace(/\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP(?:\(\d+\))?/gi, '')
    .replace(/\s+AFTER\s+"?[A-Za-z0-9_]+"?/gi, '').replace(/\s+ENGINE\s*=\s*\w+/gi, '')
    .replace(/\s+DEFAULT\s+CHARSET\s*=\s*\w+/gi, '').replace(/\s+COLLATE\s*=\s*\w+/gi, '')
    .replace(/"([^"]*)"/g, "'$1'")
    .replace(/\bNOW\(\)/gi, 'CURRENT_TIMESTAMP').replace(/\bCURDATE\(\)/gi, 'CURRENT_DATE')
    .replace(/\bVALUES\s*\(\s*([A-Za-z0-9_]+)\s*\)/gi, 'EXCLUDED.$1')
    .replace(/GROUP_CONCAT\s*\(\s*DISTINCT\s+(\w+)\s+ORDER\s+BY\s+\1\s+SEPARATOR\s+['"]\\\\['"]\s*\)/gi, "STRING_AGG(DISTINCT $1, '\\\\' ORDER BY $1)")
    .replace(/\s+CHECK\s*\(\s*json_valid\s*\([^)]*\)\s*\)/gi, '');
  sql = sql.replace(/\bALTER\s+TABLE\s+(\S+)\s+ADD\s+COLUMN\s+(?!IF\s+NOT\s+EXISTS)/gi, 'ALTER TABLE $1 ADD COLUMN IF NOT EXISTS ');
  if (/CREATE\s+TABLE/i.test(sql)) {
    sql = sql.replace(/,\s*(?:INDEX|KEY)(?:\s+\w+)?\s*\([^)]*\)/gi, '')
      .replace(/,\s*UNIQUE\s+KEY\s+\w+\s*\(([^)]*)\)/gi, ', UNIQUE ($1)');
  }
  return sql;
}

function expandParams(sql: string, params: any[] = []) {
  const values: any[] = []; let index = 0;
  const text = sql.replace(/\?/g, () => {
    const value = params[index++];
    if (Array.isArray(value) && value.length && Array.isArray(value[0])) {
      return value.map((row: any[]) => `(${row.map((cell) => {
        values.push(cell); return `$${values.length}`;
      }).join(', ')})`).join(', ');
    }
    if (Array.isArray(value)) {
      return value.map((cell) => { values.push(cell); return `$${values.length}`; }).join(', ');
    }
    values.push(value); return `$${values.length}`;
  });
  return { text, values };
}

async function prepare(client: Pool | PoolClient, input: string, params: any[]) {
  let sql = translateSql(input);
  if (/ON\s+DUPLICATE\s+KEY\s+UPDATE/i.test(sql)) {
    const table = sql.match(/INSERT\s+INTO\s+"?([A-Za-z0-9_]+)"?/i)?.[1];
    const insertedColumns = new Set(
      (sql.match(/INSERT\s+INTO\s+"?[A-Za-z0-9_]+"?\s*\(([^)]*)\)/i)?.[1] || '')
        .split(',').map(column => column.trim().replace(/^"|"$/g, '')).filter(Boolean),
    );
    const keys = table ? await client.query(`
      SELECT array_agg(a.attname ORDER BY x.ord) columns FROM pg_index i
      JOIN LATERAL unnest(i.indkey) WITH ORDINALITY x(attnum, ord) ON true
      JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum=x.attnum
      WHERE i.indrelid=$1::regclass AND (i.indisprimary OR i.indisunique)
      GROUP BY i.indexrelid`, [table]) : null;
    const columns: string[] = (keys?.rows || [])
      .map(row => Array.isArray(row.columns)
        ? row.columns
        : String(row.columns || '').replace(/^\{|\}$/g, '').split(',').filter(Boolean))
      .filter(candidate => candidate.length && candidate.every((column: string) => insertedColumns.has(column)))
      .sort((a, b) => a.length - b.length)[0] || [];
    if (!columns.length) throw new Error(`No PostgreSQL unique key for upsert table ${table}`);
    sql = sql.replace(/ON\s+DUPLICATE\s+KEY\s+UPDATE/i, `ON CONFLICT (${columns.map(c => `"${c}"`).join(', ')}) DO UPDATE SET`);
    if (table) {
      sql = sql.replace(/COALESCE\(\s*(EXCLUDED\.[A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)\s*\)/gi, `COALESCE($1, ${table}.$2)`);
      sql = sql.replace(/COALESCE\(\s*([A-Za-z0-9_]+)\s*,\s*(EXCLUDED\.[A-Za-z0-9_]+)\s*\)/gi, `COALESCE(${table}.$1, $2)`);
    }
  }
  return expandParams(sql, params);
}

const idColumnCache = new Map<string, boolean>();
async function hasIdColumn(client: Pool | PoolClient, sql: string): Promise<boolean> {
  const table = sql.match(/INSERT\s+INTO\s+"?([A-Za-z0-9_]+)"?/i)?.[1];
  if (!table) return false;
  if (idColumnCache.has(table)) return idColumnCache.get(table)!;
  const result = await client.query(
    `SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name=$1 AND column_name='id') AS present`,
    [table],
  );
  const present = Boolean(result.rows[0]?.present);
  idColumnCache.set(table, present);
  return present;
}

function wrap(client: Pool | PoolClient, release = () => {}) {
  return {
    async query(sql: string, params: any[] = []): Promise<any> {
      const prepared = await prepare(client, sql, params);
      if (/^\s*INSERT\s+/i.test(prepared.text) && !/\bRETURNING\b/i.test(prepared.text) && await hasIdColumn(client, prepared.text)) {
        prepared.text += ' RETURNING id';
      }
      let result;
      try {
        result = await client.query(prepared.text, prepared.values);
      } catch (error: any) {
        error.message += `\nPostgreSQL SQL: ${prepared.text}`;
        throw error;
      }
      if (/^\s*(SELECT|WITH)\b/i.test(prepared.text)) return [result.rows, result.fields];
      return [{ affectedRows: result.rowCount || 0, insertId: result.rows[0]?.id || 0 }, result.fields];
    },
    async beginTransaction() { await client.query('BEGIN'); },
    async commit() { await client.query('COMMIT'); },
    async rollback() { await client.query('ROLLBACK'); },
    release,
  };
}

export function createPool(config: any): any {
  const pool = new Pool({ host: config.host, port: config.port, user: config.user, password: config.password, database: config.database, max: config.connectionLimit || 10 });
  const api: any = wrap(pool);
  api.getConnection = async () => { const client = await pool.connect(); return wrap(client, () => client.release()); };
  api.end = () => pool.end();
  return api;
}
